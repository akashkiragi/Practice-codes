package com.kiragi.utils;

public class MathUtils {

	public int addTwoNm(int a, int b) {
		return a+b;
	}

	public Double calculateAreOfCirecle(int radius) {
		return 3.142*radius*radius;
	}
	
	public int diffrenceOfTwo(int a, int b) {
		return a>b? a-b: b-a;
	}
	
	public int multiplyTwoNum(int a, int b) {
		return a*b;
	}
	
	public int divideTwoNm(int a, int b) {
		return a/b;
	}
}
